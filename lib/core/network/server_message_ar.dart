/// يترجم رسائل الخطأ الإنجليزية القادمة من خدمات الباك إند إلى نص عربي.
///
/// خدمات السكن/الغروبات/المصادقة لا توفّر رسائل مُعرَّبة، فبدون هذه
/// الطبقة يظهر نص إنجليزي خام داخل تطبيق عربي بالكامل (مثال:
/// `"You must have an approved housing request to create a group"`).
///
/// القاعدة:
/// - نص فيه حروف عربية أصلاً → يُعاد كما هو (بعض النقاط ترجع عربي).
/// - نص يطابق عبارة إنجليزية معروفة → تُعاد ترجمتها العربية.
/// - نص لاتيني غير معروف → يُعاد [fallback] العربي حتى لا يظهر أي
///   إنجليزي للمستخدم إطلاقاً.
library;

const String _defaultFallback =
    'تعذّر تنفيذ العملية، يرجى مراجعة البيانات والمحاولة مرة أخرى.';

/// يحوّل [raw] (رسالة الخادم كما وصلت) إلى نص عربي صالح للعرض مباشرة.
/// يعيد [fallback] إذا كانت الرسالة فارغة أو إنجليزية غير معروفة.
String translateServerMessageAr(
  String? raw, {
  String fallback = _defaultFallback,
}) {
  final text = raw?.trim() ?? '';
  if (text.isEmpty) return fallback;

  // الخادم أحياناً يرجع عربي جاهز — لا نلمسه.
  if (_containsArabic(text)) return text;

  final lower = text.toLowerCase();
  for (final entry in _phrases.entries) {
    if (lower.contains(entry.key)) return entry.value;
  }

  // نص لاتيني غير معروف: لا نعرضه للمستخدم، نعطيه البديل العربي.
  if (_containsLatinLetters(lower)) return fallback;

  // نص بلا حروف لاتينية ولا عربية (أرقام/رموز فقط) — غير مفيد أصلاً.
  return fallback;
}

bool _containsArabic(String s) => RegExp(r'[؀-ۿ]').hasMatch(s);

bool _containsLatinLetters(String s) => RegExp(r'[a-z]').hasMatch(s);

